"""
Generate netbox_ssh_fingerprint/policy_data.py from the algorithm database of ssh-audit.

    uvx --with ssh-audit python tools/update_policy.py

Review the diff before committing. tests/test_policy_drift.py fails when the committed file no longer
matches the installed ssh-audit; the scheduled CI workflow runs it against the latest release.
"""
import sys
from pathlib import Path

from ssh_audit.globals import VERSION
from ssh_audit.ssh2_kexdb import SSH2_KexDB as DB

# Failure reasons that make an algorithm weak here. Deliberately not included: ssh-audit's verdict on
# the NIST P-curves (FAIL_NSA_BACKDOORED_CURVE), a matter of trust rather than a known break, and
# FAIL_UNKNOWN / FAIL_UNPROVEN / FAIL_UNTRUSTED.
WEAK_FAILS = {
    DB.FAIL_1024BIT_MODULUS, DB.FAIL_3DES, DB.FAIL_BLOWFISH, DB.FAIL_CAST, DB.FAIL_DES, DB.FAIL_IDEA,
    DB.FAIL_LOGJAM_ATTACK, DB.FAIL_MD5, DB.FAIL_PLAINTEXT, DB.FAIL_RC4, DB.FAIL_RIJNDAEL, DB.FAIL_RIPEMD,
    DB.FAIL_SEED, DB.FAIL_SERPENT, DB.FAIL_SHA1, DB.FAIL_SMALL_ECC_MODULUS,
}
# Warnings that also count as weak: CBC mode and 64-bit MAC tags
WEAK_WARNS = {DB.WARN_CIPHER_MODE, DB.WARN_TAG_SIZE}
PQ_INFOS = {DB.INFO_HYBRID_PQ_X25519_KEX, DB.INFO_HYBRID_PQ_NISTP_KEX}

CATEGORIES = {'kex': 'kex', 'key': 'hostkey', 'enc': 'cipher', 'mac': 'mac'}

OUT = Path(__file__).resolve().parent.parent / 'netbox_ssh_fingerprint' / 'policy_data.py'


def _field(entry, index):
    return set(entry[index]) if len(entry) > index and entry[index] else set()


def build():
    db = DB.MASTER_DB
    weak = {}
    for source, category in CATEGORIES.items():
        names = {}
        for name, entry in db[source].items():
            reasons = sorted((_field(entry, 1) & WEAK_FAILS) | (_field(entry, 2) & WEAK_WARNS))
            if reasons:
                names[name] = reasons[0]
        weak[category] = dict(sorted(names.items()))
    pq = sorted(name for name, entry in db['kex'].items() if _field(entry, 3) & PQ_INFOS)
    return VERSION, pq, weak


def render(version, pq, weak):
    lines = [
        f'# Generated by tools/update_policy.py from ssh-audit {version}. Do not edit; rerun the tool.',
        f'SOURCE = {f"ssh-audit {version}"!r}',
        '',
        '# Hybrid post-quantum key exchanges',
        'PQ_KEX = {',
        *[f'    {name!r},' for name in pq],
        '}',
        '',
        '# Weak algorithms per category, with the main reason',
        'WEAK = {',
    ]
    for category, names in weak.items():
        lines.append(f'    {category!r}: {{')
        lines += [f'        {name!r}: {reason!r},' for name, reason in names.items()]
        lines.append('    },')
    lines.append('}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    OUT.write_text(render(*build()))
    print(f'wrote {OUT} from ssh-audit {build()[0]}', file=sys.stderr)
